#ifndef POSEPRIV_MOTION_STATS_PACKET_H
#define POSEPRIV_MOTION_STATS_PACKET_H

/* 128-bit AXI4-Stream contract for temporal_motion_stats_axis_ip. */
#define POSEPRIV_MOTION_STATS_AXIS_BEAT_BYTES 16U
#define POSEPRIV_MOTION_STATS_METRIC_BITS 35U
#define POSEPRIV_MOTION_STATS_COUNT_BITS 16U
#define POSEPRIV_MOTION_STATS_SUM_BITS \
    (POSEPRIV_MOTION_STATS_METRIC_BITS + POSEPRIV_MOTION_STATS_COUNT_BITS)

#define POSEPRIV_MOTION_STATS_INPUT_ACCEL_SHIFT 70U
#define POSEPRIV_MOTION_STATS_INPUT_JOINT_SHIFT 105U
#define POSEPRIV_MOTION_STATS_INPUT_VIEW_SHIFT 113U

#define POSEPRIV_MOTION_STATS_OUTPUT_SUM_SHIFT 0U
#define POSEPRIV_MOTION_STATS_OUTPUT_MAX_SHIFT \
    POSEPRIV_MOTION_STATS_SUM_BITS
#define POSEPRIV_MOTION_STATS_OUTPUT_COUNT_SHIFT \
    (POSEPRIV_MOTION_STATS_SUM_BITS + POSEPRIV_MOTION_STATS_METRIC_BITS)
#define POSEPRIV_MOTION_STATS_OUTPUT_JOINT_SHIFT \
    (POSEPRIV_MOTION_STATS_OUTPUT_COUNT_SHIFT + POSEPRIV_MOTION_STATS_COUNT_BITS)
#define POSEPRIV_MOTION_STATS_OUTPUT_VIEW_SHIFT \
    (POSEPRIV_MOTION_STATS_OUTPUT_JOINT_SHIFT + 8U)

#endif
