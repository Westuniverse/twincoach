#ifndef POSEPRIV_AVATAR_PACKET_H
#define POSEPRIV_AVATAR_PACKET_H

/* Shared constants for the A53/Linux driver to PL avatar-skinning packet. */
#define POSEPRIV_AVATAR_PACKET_ABI_VERSION 1U
#define POSEPRIV_AVATAR_AXIS_BEAT_BYTES 16U
#define POSEPRIV_AVATAR_MATRIX_COUNT 16U
#define POSEPRIV_AVATAR_MATRIX_BEATS_PER_RECORD 2U
#define POSEPRIV_AVATAR_MATRIX_PREAMBLE_BEATS \
    (POSEPRIV_AVATAR_MATRIX_COUNT * POSEPRIV_AVATAR_MATRIX_BEATS_PER_RECORD)
#define POSEPRIV_AVATAR_MATRIX_PREAMBLE_BYTES \
    (POSEPRIV_AVATAR_MATRIX_PREAMBLE_BEATS * POSEPRIV_AVATAR_AXIS_BEAT_BYTES)
#define POSEPRIV_AVATAR_VERTEX_INPUT_BYTES 16U
#define POSEPRIV_AVATAR_VERTEX_OUTPUT_BYTES 16U
#define POSEPRIV_AVATAR_SKINNED_POINT_BYTES 8U
#define POSEPRIV_AVATAR_Q14_FRACTION_BITS 14U
#define POSEPRIV_AVATAR_Q14_ONE (1U << POSEPRIV_AVATAR_Q14_FRACTION_BITS)
/* Skinning weights use unsigned Q0.15 and must sum to 1.0 (=32768). */
#define POSEPRIV_AVATAR_WEIGHT_Q15_ONE (1U << 15U)

#endif
