#!/usr/bin/env python3
"""Emit a deterministic SV fixture from the independent integer lighting golden."""
from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from posepriv_coach.avatar_triangle_lighting_fixed import triangle_lighting_fixed

FIXTURE = ROOT / "sim/rtl/avatar_triangle_lighting_vectors.svh"


def cases():
    q = 1 << 22
    lo, hi = -(1 << 23), (1 << 23) - 1
    boundary = [
        ((0, 0, 0), (q, 0, 0), (0, q, 0)),
        ((0, 0, 0), (0, q, 0), (q, 0, 0)),
        ((0, 0, 0), (1, 0, 0), (0, 17, 0)),
        ((0, 0, 0), (1, 0, 0), (0, 18, 0)),
        ((lo, lo, lo), (hi, hi, lo), (lo, hi, hi)),
        ((hi, lo, hi), (lo, hi, lo), (hi, hi, hi)),
        ((lo, lo, lo), (lo, lo, lo), (lo, lo, lo)),
        ((hi, hi, hi), (hi, hi, hi), (hi, hi, hi)),
        ((0, 0, 0), (4194, 0, 0), (0, 0, 0)),  # thin-face collapse negative case
    ]
    for points in boundary:
        for rgb in ((0, 0, 0), (255, 255, 255), (116, 154, 38), (1, 127, 254)):
            yield points, rgb
    # Exact integer normal parallel to the quantized lamp: intensity clips to
    # 1.0. With sum(z)=0, colors 10/30/50 hit even/odd RGB rounding ties.
    by = (-24904 * pow(18022, -1, 11469)) % 11469
    bx = (18022 * by + 24904) // 11469
    aligned = ((0, 0, 1), (18022, 11469, 1), (3 * bx, 3 * by, -2))
    yield aligned, (10, 30, 50)
    yield (aligned[0], aligned[2], aligned[1]), (10, 30, 50)
    rng = random.Random(3136)
    for index in range(512):
        bound = (1, 31, 1024, q, hi)[index % 5]
        points = tuple(tuple(rng.randint(-bound, bound) for _ in range(3)) for _ in range(3))
        if index % 11 == 0:
            points = points[0], points[1], points[0]
        yield points, tuple(rng.randrange(256) for _ in range(3))


def input_word(points, rgb, face_id):
    word = sum((value & 0xffffff) << (24 * i) for i, value in enumerate(sum(points, ())))
    word |= sum(value << (216 + 8 * i) for i, value in enumerate(rgb))
    return word | (face_id << 240)


def result_word(points, rgb, face_id):
    result = triangle_lighting_fixed(points, rgb)
    color = sum(value << (8 * i) for i, value in enumerate(result.color_bgr8))
    length = 0 if result.degenerate else result.length_floor
    return (color | (result.light_q15 << 24) | (face_id << 40)
        | (int(result.degenerate) << 56) | (length << 58))


def render_fixture():
    entries = list(cases())
    lines = ["// Generated by scripts/make_avatar_triangle_lighting_fixture.py; seed 3136.",
        f"localparam int VECTOR_COUNT = {len(entries)};"]
    for name, width, function in (("vector_input", 256, input_word), ("vector_expected", 128, result_word)):
        lines += [f"function automatic logic [{width - 1}:0] {name}(input int index);", "    case (index)"]
        for index, (points, rgb) in enumerate(entries):
            word = function(points, rgb, (index * 997) & 0xffff)
            lines.append(f"        {index}: {name} = {width}'h{word:0{width // 4}x};")
        lines += [f"        default: {name} = '0;", "    endcase", "endfunction"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = render_fixture()
    if args.check:
        if not FIXTURE.is_file() or FIXTURE.read_text(encoding="utf-8") != data:
            raise SystemExit("lighting RTL fixture differs from deterministic software golden")
        print(f"lighting fixture: PASS ({len(list(cases()))} software-golden cases)")
    else:
        sys.stdout.write(data)


if __name__ == "__main__":
    main()
